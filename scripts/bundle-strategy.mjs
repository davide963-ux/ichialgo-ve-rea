/**
 * Compile the strategy to one ES module the server can import.
 *
 *   src/services/strategy/serverEntry.ts  ──esbuild──▶  server/strategy.bundle.mjs
 *
 * The scanner needs `analyseIchimoku` and `ticketLevels`. Those live in
 * TypeScript under src/ and the Vercel function is JavaScript, so something
 * has to bridge the two. The alternative — writing the rules a second time in
 * .mjs — is how a scanner and a page come to disagree about what a signal is,
 * which this project has already lived through once.
 *
 * Run as part of `npm run build`, BEFORE `vite build`, so that both outputs
 * come from the same source tree in the same build. The bundle is generated,
 * so it is git-ignored: there is never a stale committed copy to drift from
 * src/.
 */
import { build } from 'esbuild';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outfile = path.join(root, 'server', 'strategy.bundle.mjs');

mkdirSync(path.dirname(outfile), { recursive: true });

const result = await build({
  entryPoints: [path.join(root, 'src', 'services', 'strategy', 'serverEntry.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  // Node 20+, matching package.json engines and the Vercel runtime.
  platform: 'node',
  target: 'node20',
  // Keep it readable: this file gets stack traces in production logs, and a
  // minified one would name nothing useful.
  minify: false,
  // Fail loudly rather than emit a bundle with a browser-only module quietly
  // shimmed into it.
  logLevel: 'warning',
  metafile: true,
  banner: {
    js: '// GENERATED by scripts/bundle-strategy.mjs — do not edit, do not commit.\n',
  },
});

const bytes = Object.values(result.metafile.outputs)[0]?.bytes ?? 0;
const inputs = Object.keys(result.metafile.inputs).length;
console.log(`strategy bundle: ${inputs} modules → server/strategy.bundle.mjs (${(bytes / 1024).toFixed(1)} kB)`);
